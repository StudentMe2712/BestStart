const STORAGE_KEY = 'choose_a_vibe_state_v1';

class GameState {
  constructor() {
    this.state = this.loadInitialState();
  }

  defaultState() {
    return {
      profile: {
        partnerOneName: 'Алишер',
        partnerTwoName: 'Дана',
        totalXP: 0,
        unlockedAchievementIds: [],
        selectedScratchThemeId: 'classic_silver',
        excludedBoundaries: [],
        hasCompletedOnboarding: false,
        hasSeenWalkthrough: false,
        soundEnabled: true
      },
      activeSession: null,
      finishedSessions: [],
      unlockedChapters: ['ch_01']
    };
  }

  loadInitialState() {
    try {
      const saved = localStorage.getItem(STORAGE_KEY);
      if (saved) {
        const parsed = JSON.parse(saved);
        return {
          ...this.defaultState(),
          ...parsed,
          profile: { ...this.defaultState().profile, ...(parsed.profile || {}) }
        };
      }
    } catch (e) {
      console.error('Failed to load state from localStorage:', e);
    }
    return this.defaultState();
  }

  save() {
    try {
      localStorage.setItem(STORAGE_KEY, JSON.stringify(this.state));
    } catch (e) {
      console.error('Failed to save state to localStorage:', e);
    }
  }

  reset() {
    this.state = this.defaultState();
    this.save();
  }

  get profile() { return this.state.profile; }
  get activeSession() { return this.state.activeSession; }
  set activeSession(val) { this.state.activeSession = val; this.save(); }
  get finishedSessions() { return this.state.finishedSessions; }
  get unlockedChapters() { return this.state.unlockedChapters; }

  addXP(amount) {
    if (amount <= 0) return { oldLevel: ProgressionEngine.getLevel(this.profile.totalXP), newLevel: ProgressionEngine.getLevel(this.profile.totalXP), leveledUp: false };
    const oldLevel = ProgressionEngine.getLevel(this.profile.totalXP);
    this.profile.totalXP += amount;
    const newLevel = ProgressionEngine.getLevel(this.profile.totalXP);
    this.save();
    return { oldLevel, newLevel, leveledUp: newLevel.levelNumber > oldLevel.levelNumber };
  }
}

