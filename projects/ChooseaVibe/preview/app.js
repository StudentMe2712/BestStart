const ProgressionEngine = {
  allLevels: EMBEDDED_CATALOG.levels,
  allAchievements: EMBEDDED_CATALOG.achievements,

  getLevel(xp) {
    const safeXP = Math.max(0, xp);
    const matched = [...this.allLevels].reverse().find(lvl => safeXP >= lvl.requiredXP);
    return matched || this.allLevels[0];
  },

  getNextLevel(xp) {
    const cur = this.getLevel(xp);
    if (cur.levelNumber >= this.allLevels.length) return null;
    return this.allLevels[cur.levelNumber];
  },

  getNextLevelXP(xp) {
    const next = this.getNextLevel(xp);
    return next ? next.requiredXP : null;
  },

  getProgress(xp) {
    const cur = this.getLevel(xp);
    const next = this.getNextLevel(xp);
    if (!next) return 1.0;
    const span = next.requiredXP - cur.requiredXP;
    if (span <= 0) return 1.0;
    const gained = Math.max(0, xp - cur.requiredXP);
    return Math.min(Math.max(gained / span, 0.0), 1.0);
  },

  isChapterUnlocked(chapterNumOrId, completedIds, allAdventures, extraUnlocked) {
    if (extraUnlocked && extraUnlocked.includes(chapterNumOrId)) return true;
    let chapterNum = 1;
    if (typeof chapterNumOrId === 'number') {
      chapterNum = chapterNumOrId;
    } else {
      const cleaned = String(chapterNumOrId).replace('chapter_', '').replace('ch_', '').replace('chapter', '').replace('0', '');
      chapterNum = parseInt(cleaned, 10) || 1;
    }

    if (chapterNum === 1) return true;
    if (chapterNum === 2) {
      const ch1Advs = allAdventures.filter(a => a.chapterId === 'ch_01').map(a => a.id);
      const ch1Count = ch1Advs.filter(id => completedIds.has(id)).length;
      return ch1Count >= 3;
    }
    if (chapterNum === 3) {
      const ch2Advs = allAdventures.filter(a => a.chapterId === 'ch_02').map(a => a.id);
      const ch2Count = ch2Advs.filter(id => completedIds.has(id)).length;
      return ch2Count >= 3;
    }
    return false;
  },

  checkAchievements(currentAdventure, currentSession, allAdventures, completedIds, finishedSessions) {
    const eligible = [];
    const advMap = new Map(allAdventures.map(a => [a.id, a]));
    const completedAdventures = [...completedIds].map(id => advMap.get(id)).filter(Boolean);

    // 1. Первый шаг
    if (completedIds.size >= 1 || finishedSessions.filter(s => s.isFinished).length >= 1) {
      eligible.push('first_step');
    }

    // 2. Мастера уюта (3 домашних)
    const homeCount = completedAdventures.filter(a => a.location === 'Дома').length;
    if (homeCount >= 3) {
      eligible.push('cozy_masters');
    }

    // 3. Ветер перемен (1 вне дома)
    const outsideCount = completedAdventures.filter(a => a.location === 'Вне дома').length;
    if (outsideCount >= 1) {
      eligible.push('wind_of_change');
    }

    // 4. Чистая импровизация (Спонтанное без пропусков)
    const hasFlawlessSpontaneous = finishedSessions.some(s => {
      if (!s.isFinished) return false;
      const adv = advMap.get(s.adventureId);
      if (!adv || !adv.vibes.includes('Спонтанное')) return false;
      const hadSkips = s.stepStatuses.includes('skipped');
      const completedSteps = s.stepStatuses.filter(st => st === 'completed').length;
      return !hadSkips && completedSteps === s.stepStatuses.length;
    });
    if (hasFlawlessSpontaneous) {
      eligible.push('pure_improvisation');
    }

    // 5. Бесценный вечер (бюджет 0 ₸)
    const freeCount = completedAdventures.filter(a => a.budget === 0).length;
    if (freeCount >= 1) {
      eligible.push('priceless_evening');
    }

    // 6. Никаких секретов (Глубокое)
    const deepCount = completedAdventures.filter(a => a.vibes.includes('Глубокое')).length;
    if (deepCount >= 1) {
      eligible.push('no_secrets');
    }

    // 7. Глава закрыта (все 4 квеста любой главы)
    const ch1 = allAdventures.filter(a => a.chapterId === 'ch_01').map(a => a.id);
    const ch2 = allAdventures.filter(a => a.chapterId === 'ch_02').map(a => a.id);
    const ch3 = allAdventures.filter(a => a.chapterId === 'ch_03').map(a => a.id);
    const isFull = (arr) => arr.length >= 4 && arr.every(id => completedIds.has(id));
    if (isFull(ch1) || isFull(ch2) || isFull(ch3)) {
      eligible.push('chapter_closed');
    }

    // 8. Идеальная волна (3 квеста подряд по 4 карточки без пропусков)
    const finished = finishedSessions.filter(s => s.isFinished);
    let streak = 0;
    let perfectWaveWon = false;
    for (const s of finished) {
      const hadSkips = s.stepStatuses.includes('skipped');
      const completedSteps = s.stepStatuses.filter(st => st === 'completed').length;
      if (!hadSkips && completedSteps >= 4) {
        streak++;
        if (streak >= 3) {
          perfectWaveWon = true;
          break;
        }
      } else {
        streak = 0;
      }
    }
    if (perfectWaveWon) {
      eligible.push('perfect_wave');
    }

    return eligible;
  }
};

