  startAdventureSession(adventure) {
    const isReplay = State.finishedSessions.some(s => s.adventureId === adventure.id);
    const newSession = {
      adventureId: adventure.id,
      startedAt: new Date().toISOString(),
      completedAt: null,
      currentStepIndex: 1,
      isCurrentCardScratched: false,
      isUsingFallbackOnCurrentStep: false,
      stepStatuses: ['pending', 'pending', 'pending', 'pending'],
      earnedXP: 0,
      isFinished: false,
      isReplay
    };
    State.activeSession = newSession;
    this.resumeActiveSession();
  }

  resumeActiveSession() {
    const session = State.activeSession;
    if (!session) return;
    const adventure = EMBEDDED_CATALOG.adventures.find(a => a.id === session.adventureId);
    if (!adventure) return;

    this.showScreen('screen-scratch');
    this.setupScratchStep(session, adventure);
  }

  setupScratchStep(session, adventure) {
    const stepIdx = session.currentStepIndex;
    const cardIdx = stepIdx - 1;
    const card = adventure.cards[cardIdx];

    for (let i = 1; i <= 4; i++) {
      const dot = document.getElementById(`scratch-step-dot-${i}`);
      dot.className = 'step-dot';
      if (i < stepIdx) dot.classList.add('completed');
      else if (i === stepIdx) dot.classList.add('active');
    }
    document.getElementById('scratch-step-text').textContent = `Этап ${stepIdx} из 4`;

    const isPartnerOne = stepIdx % 2 !== 0;
    const currentName = isPartnerOne ? State.profile.partnerOneName : State.profile.partnerTwoName;
    const avatar = document.getElementById('scratch-turn-avatar');
    avatar.className = `turn-avatar ${isPartnerOne ? 'partner-1' : 'partner-2'}`;
    document.getElementById('scratch-partner-turn-name').textContent = `Ход ${currentName}`;
    document.getElementById('scratch-turn-instruction').textContent = session.isCurrentCardScratched
      ? 'Задание открыто — выполняйте вместе!'
      : 'Стирай защитный слой пальцем или мышкой!';

    const primary = card.primary;
    const fallback = card.fallback;

    document.getElementById('front-task-title').textContent = primary.title;
    document.getElementById('front-task-time').textContent = `~${primary.estimatedMinutes || 10} мин`;
    document.getElementById('front-task-instruction').textContent = primary.instruction;
    document.getElementById('front-task-hint').textContent = primary.hint || 'Включайте фантазию и поддерживайте друг друга!';

    document.getElementById('back-task-title').textContent = fallback.title;
    document.getElementById('back-task-time').textContent = `~${fallback.estimatedMinutes || 10} мин`;
    document.getElementById('back-task-instruction').textContent = fallback.instruction;
    document.getElementById('back-task-hint').textContent = fallback.hint || 'Пробуйте альтернативный подход!';

    this.card3dInner.classList.remove('flipped');
    if (session.isUsingFallbackOnCurrentStep) {
      this.card3dInner.classList.add('flipped');
    }

    const btnComplete = document.getElementById('btn-complete-step');
    const btnFlip = document.getElementById('btn-flip-fallback');
    const btnSkip = document.getElementById('btn-skip-step');
    const btnQuickReveal = document.getElementById('btn-quick-reveal');

    const updateButtons = (scratched) => {
      btnComplete.disabled = !scratched;
      btnFlip.disabled = !scratched;
      btnSkip.disabled = !scratched;
      btnQuickReveal.style.display = scratched ? 'none' : 'block';
      const xpAmount = session.isReplay ? 5 : 10;
      document.getElementById('btn-complete-step-label').textContent = `✦ Мы сделали это! (+${xpAmount} XP) ›`;
    };

    updateButtons(session.isCurrentCardScratched);

    if (this.scratchController) {
      this.scratchController.destroy();
    }

    this.scratchController = new ScratchCanvasController(this.scratchCanvas, () => {
      session.isCurrentCardScratched = true;
      State.save();
      updateButtons(true);
      document.getElementById('scratch-turn-instruction').textContent = 'Задание открыто — выполняйте вместе!';
    });

    if (session.isCurrentCardScratched) {
      this.scratchCanvas.classList.add('revealed');
    } else {
      setTimeout(() => {
        this.scratchController.initTexture(State.profile.selectedScratchThemeId, stepIdx, currentName);
      }, 50);
    }
  }

  completeStep() {
    Sound.playSuccess();
    const session = State.activeSession;
    if (!session) return;
    const cardIdx = session.currentStepIndex - 1;
    session.stepStatuses[cardIdx] = 'completed';
    const xpGain = session.isReplay ? 5 : 10;
    session.earnedXP += xpGain;
    const res = State.addXP(xpGain);
    if (res.leveledUp) {
      Sound.playFanfare();
      this.showLevelUpToast(res.newLevel);
    }
    this.advanceStepOrFinish();
  }

  skipStep() {
    Sound.playHaptic();
    const session = State.activeSession;
    if (!session) return;
    const cardIdx = session.currentStepIndex - 1;
    session.stepStatuses[cardIdx] = 'skipped';
    State.save();
    this.advanceStepOrFinish();
  }

  advanceStepOrFinish() {
    const session = State.activeSession;
    const adventure = EMBEDDED_CATALOG.adventures.find(a => a.id === session.adventureId);
    if (session.currentStepIndex < 4) {
      session.currentStepIndex++;
      session.isCurrentCardScratched = false;
      session.isUsingFallbackOnCurrentStep = false;
      State.save();
      this.setupScratchStep(session, adventure);
    } else {
      this.finishAdventureSession(session, adventure);
    }
  }

  finishAdventureSession(session, adventure) {
    session.isFinished = true;
    session.completedAt = new Date().toISOString();
    const finishBonus = session.isReplay ? 15 : 25;
    session.earnedXP += finishBonus;
    State.addXP(finishBonus);

    State.finishedSessions.push(JSON.parse(JSON.stringify(session)));

    const allCompletedIds = new Set(State.finishedSessions.map(s => s.adventureId));
    const eligibleIds = ProgressionEngine.checkAchievements(
      adventure,
      session,
      EMBEDDED_CATALOG.adventures,
      allCompletedIds,
      State.finishedSessions
    );

    const newlyUnlocked = [];
    eligibleIds.forEach(id => {
      if (!State.profile.unlockedAchievementIds.includes(id)) {
        State.profile.unlockedAchievementIds.push(id);
        State.addXP(20);
        const achDef = EMBEDDED_CATALOG.achievements.find(a => a.id === id);
        if (achDef) newlyUnlocked.push(achDef);
      }
    });

    State.activeSession = null;
    State.save();

    Sound.playFanfare();
    this.showCelebration(session, adventure, newlyUnlocked, finishBonus);
  }

  showCelebration(session, adventure, newAchievements, finishBonus) {
    this.showScreen('screen-celebration');
    this.confetti.burst(130);

    document.getElementById('celebration-quest-name').textContent = `«${adventure.title}»`;
    const stepsXP = session.earnedXP - finishBonus;
    document.getElementById('summary-steps-xp').textContent = `+${stepsXP} XP`;
    document.getElementById('summary-finish-bonus-xp').textContent = `+${finishBonus} XP`;

    const achRow = document.getElementById('summary-achievements-xp-row');
    if (newAchievements.length > 0) {
      achRow.style.display = 'flex';
      document.getElementById('summary-achievements-xp').textContent = `+${newAchievements.length * 20} XP`;
    } else {
      achRow.style.display = 'none';
    }

    const grandTotal = session.earnedXP + (newAchievements.length * 20);
    document.getElementById('summary-total-xp').textContent = `+${grandTotal} XP`;

    const badgesContainer = document.getElementById('celebration-badges-container');
    badgesContainer.innerHTML = '';
    if (newAchievements.length > 0) {
      newAchievements.forEach(ach => {
        const item = document.createElement('div');
        item.className = 'new-badge-item';
        item.innerHTML = `
          <svg viewBox="0 0 24 24" fill="currentColor"><path d="M12 2l3.09 6.26L22 9.27l-5 4.87 1.18 6.88L12 17.77l-6.18 3.25L7 14.14 2 9.27l6.91-1.01L12 2z"/></svg>
          <div class="new-badge-item-info">
            <span class="new-badge-item-title">Новый значок: «${ach.title}»! (+20 XP)</span>
            <span class="new-badge-item-desc">${ach.description}</span>
          </div>
        `;
        badgesContainer.appendChild(item);
      });
    }
  }
