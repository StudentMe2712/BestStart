// 5. VIBE MATCHER SERVICE (Exact VibeMatcherService.swift Weighted Soft-Matching)
// =============================================================================
const VibeMatcherService = {
  areAdjacentDurations(a, b) {
    const pairs = [
      ['15–30 мин', '30–60 мин'],
      ['30–60 мин', '15–30 мин'],
      ['30–60 мин', '60–120 мин'],
      ['60–120 мин', '30–60 мин']
    ];
    return pairs.some(p => p[0] === a && p[1] === b);
  },

  evaluateHardConstraints(adventure, criteria, excludedBoundaries) {
    // 1. Личные границы
    if (excludedBoundaries && excludedBoundaries.length > 0) {
      for (const card of adventure.cards) {
        const cardTags = card.boundaryTags || [];
        for (const tag of cardTags) {
          if (excludedBoundaries.includes(tag)) {
            return false;
          }
        }
      }
    }

    // 2. Локация
    if (criteria.location === 'Дома' && adventure.location === 'Вне дома') {
      return false;
    }
    if (criteria.location === 'Вне дома' && adventure.location === 'Дома') {
      return false;
    }

    // 3. Бюджет 0 ₸
    if (criteria.budget === 0 && adventure.budget > 0) {
      return false;
    }

    return true;
  },

  calculateScore(adventure, criteria, currentChapterId) {
    let score = 0;
    let vibeMatches = false;

    // 1. Вайбы
    if (adventure.vibes && adventure.vibes.length > 0) {
      const primary = adventure.vibes[0];
      if (criteria.vibes.includes(primary)) {
        score += 50;
        vibeMatches = true;
      }
      for (let i = 1; i < adventure.vibes.length; i++) {
        if (criteria.vibes.includes(adventure.vibes[i])) {
          score += 25;
          vibeMatches = true;
        }
      }
    }

    // 2. Длительность
    if (criteria.duration) {
      if (adventure.duration === criteria.duration) {
        score += 20;
      } else if (this.areAdjacentDurations(adventure.duration, criteria.duration)) {
        score += 10;
      }
    }

    // 3. Бюджет
    if (criteria.budget !== undefined && criteria.budget !== null) {
      if (adventure.budget <= criteria.budget) {
        score += 15;
      }
    }

    // 4. Текущая глава
    if (adventure.chapterId === currentChapterId) {
      score += 10;
    }

    return { score, vibeMatches };
  },

  matchAdventure(criteria, adventures, completedIds, excludedBoundaries, currentChapterId = 'ch_01') {
    if (!adventures || adventures.length === 0) {
      throw new Error('Каталог приключений пуст');
    }

    const candidates = adventures.map(adv => {
      const passesHard = this.evaluateHardConstraints(adv, criteria, excludedBoundaries);
      const { score, vibeMatches } = this.calculateScore(adv, criteria, currentChapterId);
      const isCompleted = completedIds.has(adv.id);
      return {
        adventure: adv,
        score,
        passesHard,
        vibeMatches,
        isCompleted
      };
    });

    candidates.sort((a, b) => {
      if (a.score !== b.score) return b.score - a.score;
      if (a.isCompleted !== b.isCompleted) return a.isCompleted ? 1 : -1;
      const aInCurrent = a.adventure.chapterId === currentChapterId;
      const bInCurrent = b.adventure.chapterId === currentChapterId;
      if (aInCurrent !== bInCurrent) return aInCurrent ? -1 : 1;
      if (a.adventure.orderInChapter !== b.adventure.orderInChapter) {
        return a.adventure.orderInChapter - b.adventure.orderInChapter;
      }
      return a.adventure.id.localeCompare(b.adventure.id);
    });

    // Ступень 1: Идеальное совпадение
    const exact = candidates.find(c => c.passesHard && !c.isCompleted && (criteria.vibes.length === 0 || c.vibeMatches));
    if (exact) {
      return { adventure: exact.adventure, score: exact.score, isFallbackMatch: false };
    }

    // Ступень 2: Фолбэк среди непройденных
    const uncompletedFallback = candidates.find(c => c.passesHard && !c.isCompleted);
    if (uncompletedFallback) {
      return { adventure: uncompletedFallback.adventure, score: uncompletedFallback.score, isFallbackMatch: true };
    }

    // Ступень 3: Повторное прохождение лучшего
    const completedFallback = candidates.find(c => c.passesHard && c.isCompleted);
    if (completedFallback) {
      return { adventure: completedFallback.adventure, score: completedFallback.score, isFallbackMatch: true };
    }

    // Ступень 4: Ослабленные границы (лучший непройденный)
    const relaxed = candidates.find(c => !c.isCompleted);
    if (relaxed) {
      return { adventure: relaxed.adventure, score: relaxed.score, isFallbackMatch: true };
    }

    // Ступень 5: Абсолютный фолбэк
    return { adventure: candidates[0].adventure, score: candidates[0].score, isFallbackMatch: true };
  }
};

